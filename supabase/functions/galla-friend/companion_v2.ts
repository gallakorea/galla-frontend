function pick<T>(arr: T[], n: number, seed: string): T[] {
  // 같은 말엔 같은 예시가 안 나오게 — 시각 + 말로 섞는다
  let h = 0; for (const c of seed + Date.now().toString().slice(-6)) h = (h * 31 + c.charCodeAt(0)) >>> 0;
  const a = arr.slice();
  for (let i = a.length - 1; i > 0; i--) { h = (h * 1103515245 + 12345) >>> 0; const j = h % (i + 1); [a[i], a[j]] = [a[j], a[i]]; }
  return a.slice(0, n);
}

