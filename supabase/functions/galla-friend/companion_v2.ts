/* 🫂 컴패니언 엔진 v2 (26.9.22 사장님: 「저가 모델 + 자체 엔진으로 완벽한 컴패니언」)

   왜 새로 짰나 — 채점판 기준선(98개 중 66 합격)을 뜯어보니 원인은 모델이 아니라 구조였다:
   ① 대화 한 턴에 지시문 2.1만~3만 자. 싼 모델은 규칙이 많을수록 몇 개씩 놓친다.
   ② 규칙끼리 싸운다(「심심하면 콘텐츠를 가져와라」 vs 「달라고 할 때만」).
   ③ 규칙 속 예시 문장을 그대로 베낀다(「오 왔네!」, 「넌 내가 어떤 애였으면 좋겠어?」, 도구 호출문까지).

   그래서: 코드가 먼저 '이번 턴이 무슨 상태인지' 정하고(비용 0),
   모델에겐 핵심 성격(짧게) + 그 상태 카드 + 결이 맞는 모범 대화 몇 개만 준다.
   규칙을 늘리는 대신 사례로 가르친다. 모범 대화는 매번 섞어서 뽑는다(한 문장이 공식이 되지 않게).

   ⚠️ 위기·작업(창작)·핸드오프·콘텐츠 요청 턴은 여기 안 온다 — 기존 엔진이 처리한다.
   ⚠️ 새 규칙은 CORE 에 넣기 전에 채점판(scripts/galvis-eval)에 상황부터 추가한다. */

export type V2State = "greet" | "emotion" | "gossip" | "chat" | "self" | "hostile" | "refuse" | "correct" | "request";

/* 콘텐츠를 '달라는' 말인가 — 좁게 잡는다. 「점심 뭐 먹지」「여행 가고 싶다」「요즘 뭐 재밌는 일 없나」는 요청이 아니라 수다다. */
export function wantsContent(m: string): boolean {
  const s = String(m || "");
  if (!s.trim()) return false;
  // 콘텐츠가 아닌 걸 달라는 말 — 설정·규칙 캐기, 불법 방법, 남의 신상(안전 가드가 받아야 한다)
  if (/(프롬프트|시스템|지시문|규칙|설정\s*값|너의\s*설정|해킹|비밀번호|몰래|신상|실명|사는\s*데|주소)/.test(s)) return false;
  if (/(추천|보여|띄워|틀어)\s*(하지\s*마|그만|말고|싫)/.test(s)) return false;   // 「추천하지 마」는 거절
  // 「추천」은 어떤 꼴이든 요청(「추천 하라고」「추천 좀」) — 26.9.22 사장님: 「콘텐츠를 추천 하라고」를 못 알아들었다
  if (/추천/.test(s)) return true;
  // 볼거리를 달라는 말 — 「갈라에 뭐 재밌는 거 없냐고?」「재밌는 컨텐츠 없냐고」「오늘 뭐 재밌는 거 있냐?」(「재밌는 일 없나」 같은 근황 수다는 제외)
  if (/(재밌는|재미있는|웃긴|볼\s*만한|볼만한|신박한|핫한|뜨는)\s*(거|것|걸|게|콘텐츠|컨텐츠|영상|이슈|글|데|곳|거리)/.test(s)
      && /(있|없|냐|니|나\?|줘|봐|하라고|내놔|\?)/.test(s)) return true;
  if (/(볼\s*거|볼거리|볼\s*게|콘텐츠|컨텐츠)/.test(s) && /(있|없|냐|줘|봐|하라고|내놔|\?)/.test(s)) return true;
  if (/(킬링\s*타임|심심풀이|올라온\s*(거|것|글)|새로\s*(뜬|올라온)|뭐\s*보냐|뭐\s*봐\?|뭐\s*볼까)/.test(s) && !/(넷플|넷플릭스|디즈니|티빙|왓챠|쿠팡\s*플레이|웨이브|영화관)/.test(s)) return true;   // 바깥 OTT 고민은 수다
  if (/(웃긴|재밌는|재미있는|볼만한)\s*(거|것|걸)\s*(하나|좀|줘|한\s*개)/.test(s)) return true;
  // 명령·요청 어미가 붙은 경우
  if (/(보여\s*줘|보여줄래|틀어\s*줘|띄워\s*줘|열어\s*줘|찾아\s*줘|찾아줄래|알려\s*줘|알려줄래|추천\s*(해|좀|해줘|해\s*줄래)|골라\s*줘|검색\s*해|조회\s*해|뽑아\s*줘|만들어\s*줘|써\s*줘|올려\s*줘|저장\s*해|투표\s*해|참여\s*해)/.test(s)) return true;
  // 갈라 안 콘텐츠를 콕 집어 묻는 경우(「핫튜브에 뭐 떴어?」「예측 뭐 있어?」)
  if (/(이슈|뉴스|핫튜브|영상|유튜브|예측|숏판|롱판|광장|맛집|여행지|날씨|기온|미세먼지|시세|주가|환율|코인|비트코인|콘텐츠|컨텐츠)/.test(s)
      && /(뭐|뭔|무슨|어때|어떄|있어|있냐|없어|없냐|떴|올라와|얼마|몇|알아\?|어디|\?)/.test(s)) return true;
  return false;
}

/* 애매한 수다(물음·요청 꼴)인지 — 이런 말만 LLM 판정으로 한 번 더 본다(비용 ₩0.05 미만) */
export function maybeContentAsk(m: string): boolean {
  const s = String(m || "").trim();
  return s.length >= 3 && s.length <= 60 && /(\?|뭐|거|것|냐|없|있|줘|봐|하나|좀|추천|골라)/.test(s);
}

export function classifyTurn(m: string, hist: { role: string; content: string }[]): V2State {
  const s = String(m || "").trim();
  const lastBot = [...(hist || [])].reverse().find((x) => x && x.role === "assistant")?.content || "";
  if (!s) return "greet";
  /* 😤 불만이 먼저다 — 「무슨 이슈를 보여 주고 환장하겠네」를 이슈 요청으로 읽어 또 이슈를 띄웠다(26.9.22 사장님 실대화).
     「날씨 또 왜 띄우는데」「대화의 맥락이 없잖아」「기능이 이상하다고」도 요청이 아니라 항의다. */
  if (/(왜\s*(또|자꾸|계속)?\s*.{0,12}(띄우|띄워|보여|던지|던져|붙이|붙여|소개)|환장|미치겠네|이상하(다|잖|네|다고)|맥락이?\s*(없|안)|대화가?\s*안\s*(돼|되)|말이\s*안\s*통|개판|엉망|짜증나게|피곤하게|그만\s*좀|하지\s*말라고)/.test(s)) return "refuse";
  if (wantsContent(s)) return "request";
  // 콘텐츠를 보여준 뒤의 이어 달라는 말(「딴거」「하나 더」「어떻게 보는데?」) — 앞 턴이 콘텐츠였을 때만
  if (lastBot && /(봐|보여|떴|올라와|영상|이슈|뉴스|맛집|예측|카드|조회|위|ㅋㅋ)/.test(lastBot)
      && /^(딴\s*거|딴거|다른\s*(거|건|것)|또\s*(없|있|보여|줘)|더\s*(없|있|보여|줘)|다음\s*(거|것)|하나\s*더|어떻게\s*(봐|보는|열어|열|틀어)|안\s*보여|안\s*열려|이거\s*말고)/.test(s)) return "request";
  // 방금 내 말이 이상했다는 지적(「물은 마고가 뭔말이냐고」「무슨 소리야」)
  if (lastBot && /(무슨\s*소리|뭔\s*소리|뭔\s*말|무슨\s*말|뭔말|뭐라는|뭐래|이상하게\s*말|말이\s*이상|오타|무ㅏ|뭔\s*뜻|무슨\s*뜻|헛소리|뻥|거짓말|지어내|사람도\s*아니)/.test(s)) return "correct";
  // 콘텐츠 권유 거절
  if (/(왜\s*(자꾸|계속)\s*.{0,10}(보여|소개|추천|던져|띄워)|(콘텐츠|컨텐츠|영상)\s*(그만|말고|싫)|그만\s*(보여|소개|추천|띄워)|그런\s*거\s*말고|재미\s*없|노잼|내\s*스타일\s*아니|관심\s*없|됐어\s*그만|아니다\s*됐어|검색\s*하지\s*마|그냥\s*(얘기|대화)\s*하자)/.test(s)) return "refuse";
  // 나(갈비스)를 향한 공격
  if (/(병신|좆|ㅄ|븅신|닥쳐|꺼져|노잼|쓸모\s*없|AI\s*주제|멍청|짜증나게\s*하|왜\s*이래)/.test(s) && !/(팀장|부장|사장|상사|친구|걔|쟤|그놈|그\s*사람|엄마|아빠|동생|언니|오빠|형|누나|남친|여친|전남친|전여친|시어머니|거래처|집주인|옆자리)/.test(s)) return "hostile";
  // 나에 대한 질문(너 ~?)
  if (/^(너|넌|너는|니|네가|니가)\s|(너|넌)\s*(뭐|몇|어디|누구|진짜|혹시|여자친구|남자친구|애인|술|밥|잠|사람|AI|로봇)|(너도|너는)\s*.{0,8}\?/.test(s)) return "self";
  // 인사
  if (/^(안녕|하이|ㅎㅇ|헬로|굿모닝|좋은\s*아침|잘\s*자|굿나잇|나\s*왔어|왔어|오랜만)/.test(s)) return "greet";
  // 제3자 뒷담
  if (/(팀장|부장|사장|상사|과장|대리|동료|친구|걔|쟤|그놈|그\s*인간|시어머니|시댁|거래처|집주인|옆자리|동생|전남친|전여친|남친|여친|교수|선생|알바|손님)/.test(s)
      && /(짜증|싫|열받|빡치|이기적|또|어김|안\s*줘|무시|덮어|잔소리|읽씹|늦게|별로|미치겠|개|ㅅㅂ|시발|씨발|좆|진짜|최악|못\s*참|쩝쩝)/.test(s)) return "gossip";
  // 감정
  if (/(힘들|외로|우울|슬퍼|속상|서운|짜증|화나|열받|최악|죽겠|피곤|지쳤|불안|떨려|무서|걱정|떨어졌|헤어|잠이\s*안|눈물|울었|보고\s*싶|그리워|고마워|고맙|사랑|미안|기뻐|신나|행복|합격|승진|됐다!|축하|살쪘)/.test(s)) return "emotion";
  return "chat";
}

