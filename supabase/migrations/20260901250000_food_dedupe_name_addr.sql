-- 중복이 다시 생기지 않게 세 번째 키를 건다: 정규화한 이름 + 정규화한 주소.
--
-- 기존 두 인덱스는 WHERE 조건이 서로 배타적이라(좌표 있음 / 없음) 서로를 못 본다.
-- 게다가 좌표가 있어도 네이버가 회차마다 조금 다른 값을 주면 round(,3)이 갈린다.
-- 실측 4쌍이 전부 '이름+주소 동일'이었으므로 이 키 하나로 두 구멍이 다 막힌다.
--
-- ⚠️ 부분 인덱스로 만들지 않는다 — live 11,842건 중 주소가 빈 행이 0건이라 필요가 없고,
--    조건을 달면 또 '서로 못 보는 집합'이 생긴다(지금 고치는 문제가 바로 그거다).
-- ⚠️ 같은 이름 + 같은 주소면 같은 가게다. 지점이 다르면 주소가 다르므로 정상 데이터는 안 막힌다.
create unique index if not exists food_places_dedupe_name_addr
  on food_places (norm_name, regexp_replace(coalesce(address,''), '[[:space:]]', '', 'g'));
