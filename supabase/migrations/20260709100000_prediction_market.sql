-- 갈라예측: 폴리마켓식 예측시장 (가상 포인트, CPMM)
-- 2026-07-09 Management API로 원격 적용 (기록용)

-- ============ 테이블 ============
create table if not exists public.markets (
  id            bigint generated by default as identity primary key,
  question      text not null,
  description   text,
  category      text,
  image_url     text,
  created_by    uuid references auth.users(id) on delete set null,
  created_at    timestamptz not null default now(),
  close_at      timestamptz not null,
  resolved      boolean not null default false,
  outcome       text check (outcome in ('yes','no')),
  resolved_at   timestamptz,
  -- CPMM 상태 (가상 유동성)
  pool_yes      double precision not null default 1000,
  pool_no       double precision not null default 1000,
  volume        double precision not null default 0,
  status        text not null default 'open'
);
create index if not exists markets_category_idx on public.markets (category);
create index if not exists markets_close_idx on public.markets (close_at);

create table if not exists public.point_balances (
  user_id          uuid primary key references auth.users(id) on delete cascade,
  balance          double precision not null default 10000,
  last_daily_claim date,
  updated_at       timestamptz not null default now()
);

create table if not exists public.market_positions (
  id          bigint generated by default as identity primary key,
  market_id   bigint not null references public.markets(id) on delete cascade,
  user_id     uuid not null references auth.users(id) on delete cascade,
  yes_shares  double precision not null default 0,
  no_shares   double precision not null default 0,
  spent       double precision not null default 0,
  unique (market_id, user_id)
);
create index if not exists positions_market_idx on public.market_positions (market_id);
create index if not exists positions_user_idx on public.market_positions (user_id);

create table if not exists public.market_trades (
  id            bigint generated by default as identity primary key,
  market_id     bigint not null references public.markets(id) on delete cascade,
  user_id       uuid references auth.users(id) on delete set null,
  side          text not null check (side in ('yes','no')),
  spend         double precision not null,
  shares        double precision not null,
  price_yes     double precision not null,   -- 거래 직후 YES 확률
  created_at    timestamptz not null default now()
);
create index if not exists trades_market_idx on public.market_trades (market_id, created_at);

create table if not exists public.point_ledger (
  id         bigint generated by default as identity primary key,
  user_id    uuid not null references auth.users(id) on delete cascade,
  delta      double precision not null,
  reason     text not null,
  market_id  bigint,
  created_at timestamptz not null default now()
);

-- ============ RLS (읽기 공개, 쓰기는 RPC(security definer)로만) ============
alter table public.markets enable row level security;
alter table public.point_balances enable row level security;
alter table public.market_positions enable row level security;
alter table public.market_trades enable row level security;
alter table public.point_ledger enable row level security;

drop policy if exists "markets read" on public.markets;
create policy "markets read" on public.markets for select using (true);

drop policy if exists "positions read" on public.market_positions;
create policy "positions read" on public.market_positions for select using (true);

drop policy if exists "trades read" on public.market_trades;
create policy "trades read" on public.market_trades for select using (true);

drop policy if exists "balance read own" on public.point_balances;
create policy "balance read own" on public.point_balances for select using (auth.uid() = user_id);

drop policy if exists "ledger read own" on public.point_ledger;
create policy "ledger read own" on public.point_ledger for select using (auth.uid() = user_id);

-- ============ 잔액 보장 / 일일 지급 ============
create or replace function public.ensure_balance()
returns double precision language plpgsql security definer set search_path = public as $$
declare v_bal double precision; v_user uuid := auth.uid();
begin
  if v_user is null then return null; end if;
  insert into point_balances (user_id) values (v_user)
    on conflict (user_id) do nothing;
  select balance into v_bal from point_balances where user_id = v_user;
  return v_bal;
end $$;

create or replace function public.claim_daily()
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_user uuid := auth.uid(); v_last date; v_bal double precision; v_amt double precision := 1000;
begin
  if v_user is null then return jsonb_build_object('ok', false, 'reason', 'unauthorized'); end if;
  insert into point_balances (user_id) values (v_user) on conflict (user_id) do nothing;
  select last_daily_claim, balance into v_last, v_bal from point_balances where user_id = v_user for update;
  if v_last = current_date then
    return jsonb_build_object('ok', false, 'reason', 'already', 'balance', v_bal);
  end if;
  update point_balances set balance = balance + v_amt, last_daily_claim = current_date, updated_at = now()
    where user_id = v_user returning balance into v_bal;
  insert into point_ledger (user_id, delta, reason) values (v_user, v_amt, 'daily');
  return jsonb_build_object('ok', true, 'balance', v_bal, 'claimed', v_amt);
end $$;

-- ============ 마켓 생성 ============
create or replace function public.create_market(
  p_question text, p_description text, p_category text, p_image_url text,
  p_close_at timestamptz, p_liquidity double precision default 1000
) returns bigint language plpgsql security definer set search_path = public as $$
declare v_user uuid := auth.uid(); v_id bigint; v_liq double precision;
begin
  if v_user is null then raise exception 'unauthorized'; end if;
  if p_question is null or length(trim(p_question)) = 0 then raise exception 'question required'; end if;
  if p_close_at is null or p_close_at <= now() then raise exception 'close_at must be future'; end if;
  v_liq := greatest(coalesce(p_liquidity, 1000), 100);
  insert into markets (question, description, category, image_url, created_by, close_at, pool_yes, pool_no)
  values (trim(p_question), p_description, p_category, p_image_url, v_user, p_close_at, v_liq, v_liq)
  returning id into v_id;
  return v_id;
end $$;

-- ============ 거래 (CPMM 매수) ============
-- Gnosis FPMM: buy YES with s → shares = y + s - y*n/(n+s), y'=y*n/(n+s), n'=n+s
create or replace function public.market_trade(
  p_market_id bigint, p_side text, p_spend double precision
) returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_user uuid := auth.uid();
  m record; v_bal double precision; v_shares double precision;
  v_y double precision; v_n double precision; v_k double precision;
  v_price double precision;
begin
  if v_user is null then return jsonb_build_object('ok', false, 'reason', 'unauthorized'); end if;
  if p_side not in ('yes','no') then return jsonb_build_object('ok', false, 'reason', 'bad_side'); end if;
  if p_spend is null or p_spend <= 0 then return jsonb_build_object('ok', false, 'reason', 'bad_amount'); end if;

  select * into m from markets where id = p_market_id for update;
  if m is null then return jsonb_build_object('ok', false, 'reason', 'not_found'); end if;
  if m.resolved or m.status <> 'open' or m.close_at <= now() then
    return jsonb_build_object('ok', false, 'reason', 'closed');
  end if;

  insert into point_balances (user_id) values (v_user) on conflict (user_id) do nothing;
  select balance into v_bal from point_balances where user_id = v_user for update;
  if v_bal < p_spend then return jsonb_build_object('ok', false, 'reason', 'insufficient', 'balance', v_bal); end if;

  v_y := m.pool_yes; v_n := m.pool_no; v_k := v_y * v_n;

  if p_side = 'yes' then
    v_shares := v_y + p_spend - (v_k / (v_n + p_spend));
    v_y := v_k / (v_n + p_spend);
    v_n := v_n + p_spend;
  else
    v_shares := v_n + p_spend - (v_k / (v_y + p_spend));
    v_n := v_k / (v_y + p_spend);
    v_y := v_y + p_spend;
  end if;

  v_price := v_n / (v_y + v_n);  -- 거래 직후 YES 확률

  update markets set pool_yes = v_y, pool_no = v_n, volume = volume + p_spend where id = p_market_id;

  update point_balances set balance = balance - p_spend, updated_at = now() where user_id = v_user;
  insert into point_ledger (user_id, delta, reason, market_id) values (v_user, -p_spend, 'trade', p_market_id);

  insert into market_positions (market_id, user_id, yes_shares, no_shares, spent)
  values (p_market_id, v_user,
          case when p_side='yes' then v_shares else 0 end,
          case when p_side='no'  then v_shares else 0 end,
          p_spend)
  on conflict (market_id, user_id) do update set
    yes_shares = market_positions.yes_shares + (case when p_side='yes' then v_shares else 0 end),
    no_shares  = market_positions.no_shares  + (case when p_side='no'  then v_shares else 0 end),
    spent      = market_positions.spent + p_spend;

  insert into market_trades (market_id, user_id, side, spend, shares, price_yes)
  values (p_market_id, v_user, p_side, p_spend, v_shares, v_price);

  return jsonb_build_object('ok', true, 'shares', v_shares, 'price_yes', v_price, 'balance', v_bal - p_spend);
end $$;

-- ============ 정산 (마켓 생성자만) ============
create or replace function public.market_resolve(p_market_id bigint, p_outcome text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_user uuid := auth.uid(); m record; r record; v_payout double precision; v_count int := 0;
begin
  if v_user is null then return jsonb_build_object('ok', false, 'reason', 'unauthorized'); end if;
  if p_outcome not in ('yes','no') then return jsonb_build_object('ok', false, 'reason', 'bad_outcome'); end if;
  select * into m from markets where id = p_market_id for update;
  if m is null then return jsonb_build_object('ok', false, 'reason', 'not_found'); end if;
  if m.created_by <> v_user then return jsonb_build_object('ok', false, 'reason', 'forbidden'); end if;
  if m.resolved then return jsonb_build_object('ok', false, 'reason', 'already'); end if;

  -- 이긴 셰어 1개 = 1포인트 지급
  for r in select user_id, yes_shares, no_shares from market_positions where market_id = p_market_id loop
    v_payout := case when p_outcome = 'yes' then r.yes_shares else r.no_shares end;
    if v_payout > 0 then
      insert into point_balances (user_id) values (r.user_id) on conflict (user_id) do nothing;
      update point_balances set balance = balance + v_payout, updated_at = now() where user_id = r.user_id;
      insert into point_ledger (user_id, delta, reason, market_id) values (r.user_id, v_payout, 'payout', p_market_id);
      v_count := v_count + 1;
    end if;
  end loop;

  update markets set resolved = true, outcome = p_outcome, resolved_at = now(), status = 'resolved'
    where id = p_market_id;

  return jsonb_build_object('ok', true, 'paid_users', v_count);
end $$;

