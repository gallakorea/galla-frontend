-- 수확 크론을 5분으로 되돌린다 (2026-09-02, 사장님 판단)
--
-- 오늘 아침 5분 → 2분으로 당겨 시간당 360편이 1,600편이 됐다. 그런데 그건
-- **남이 남겨둔 계산의 전제를 깬 것**이었다. travel_geo_budget 주석:
--   "Nominatim 정책의 핵심은 총량이 아니라 초당 1회이고, 런 안에서 1.1초 간격을 지키며
--    런은 5분마다라 평균 0.13회/초다. 그래도 이보다 더 올리지는 말 것 —
--    차단당하면 화면엔 아무 표시가 안 나고 수집만 조용히 멈춘다."
-- 2분 주기에서는 평균이 **0.68회/초**가 된다. 실제로 지오 예산 8,000이 반나절 만에
-- 바닥나 시간당 1,634 → 192편으로 주저앉았다(예산이 마르면 회차가 통째로 멈춘다).
--
-- 되돌린다. 함수의 시간 상자도 90초 → 110초로 같이 복구했다.
-- ⚠️ **크론 주기와 시간 상자는 한 세트다.** 하나만 바꾸면 오늘 같은 일이 또 난다.
--    5분 × 110초 = 하루 평균 0.13회/초, 지오 호출 약 4,300회 → 8,000 안에 넉넉히 든다.
--    (2분 × 90초였을 땐 0.68회/초 · 하루 12,000회 요구 = 예산 초과)
-- 속도는 시간당 ~360편으로 돌아간다. 남은 18,900편이면 약 2일이다 —
-- 예산이 마른 채로 도는 것과 총 소요는 비슷하고, 차단 위험만 없어진다.
select cron.alter_job(
  (select jobid from cron.job where jobname = 'travel_harvest_places_job'),
  schedule := '*/5 * * * *');
