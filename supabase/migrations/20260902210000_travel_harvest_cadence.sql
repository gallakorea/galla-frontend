-- 수확 크론 5분 → 2분 (2026-09-02)
--
-- 사장님: "왜 이렇게 오래 걸리지?" 재 보니 답이 명확했다.
--   · 한 회차는 시간 상자(110초)를 다 쓰고 ~30편을 처리한다
--   · 그런데 크론은 5분마다 → **시간의 63%를 놀고 있었다**
-- 편당 3.7초는 구조상 못 줄인다: 영상마다 AI 호출 1회 + 장소마다 지오코딩인데
-- Nominatim 정책이 초당 1회라 sleep(1100) 이 박혀 있다. 정책을 어기면 차단당하고
-- 그러면 수확이 통째로 멈춘다 — 여기는 손대면 안 되는 자리다.
-- 대신 **놀고 있는 시간**은 공짜로 회수할 수 있다.
--
-- ⚠️ 회차 시간 상자를 110초 → 90초로 같이 줄였다(함수 쪽). 90초 + 마무리 ≈ 100초 < 120초라
--    다음 회차와 안 겹친다. 겹치면 두 회차가 같은 채널의 같은 영상을 집어(수확 표시는
--    회차 끝에 한다) AI 호출이 낭비되고, Nominatim 을 초당 2회로 두들기게 된다.
select cron.alter_job(
  (select jobid from cron.job where jobname = 'travel_harvest_places_job'),
  schedule := '*/2 * * * *');
